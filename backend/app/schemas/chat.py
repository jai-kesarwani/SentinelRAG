"""
SentinelRAG — Chat & RAG Schemas.

Pydantic v2 schemas for conversations, messages, RAG queries, and citations.
"""
from __future__ import annotations

from datetime import datetime
from typing import Any, Optional

from pydantic import BaseModel, ConfigDict, Field


class CitationSchema(BaseModel):
    """Citation response schema."""

    document_id: str
    chunk_id: str
    page_number: int
    source_filename: str
    excerpt: Optional[str] = None


class ConversationCreateRequest(BaseModel):
    """Payload to create a new conversation."""

    title: Optional[str] = Field(default=None, max_length=120)


class ConversationResponse(BaseModel):
    """Conversation metadata response."""

    id: str
    title: str
    owner_id: str
    created_at: datetime
    updated_at: datetime

    model_config = ConfigDict(populate_by_name=True)


class ConversationListResponse(BaseModel):
    """List of conversations owned by the user."""

    conversations: list[ConversationResponse]
    total: int


class MessageCreateRequest(BaseModel):
    """User message payload to ask a question in a conversation."""

    content: str = Field(min_length=1, max_length=4000, description="User question or prompt")


class MessageResponse(BaseModel):
    """Individual message response schema."""

    id: str
    conversation_id: str
    role: str
    content: str
    citations: list[CitationSchema] = Field(default_factory=list)
    created_at: datetime
    validation_status: str

    model_config = ConfigDict(populate_by_name=True)


class ConversationDetailResponse(BaseModel):
    """Conversation metadata along with message history."""

    conversation: ConversationResponse
    messages: list[MessageResponse]


class ChatAnswerResponse(BaseModel):
    """Complete answer response generated by the RAG AI agent."""

    message: MessageResponse
    citations: list[CitationSchema]
    retrieved_chunk_count: int
    grounded: bool
    confidence: Optional[str] = "high"  # high | low | unsupported
    security_decision: Optional[str] = "allow"  # allow | block | sanitize
    is_blocked: bool = False
    blocked_reason: Optional[str] = None
    safe_summary: Optional[str] = None

