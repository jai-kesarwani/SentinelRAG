"""
SentinelRAG — Post-Generation Output Security & Sanitization Service.

Inspects raw LLM answers to protect against:
1. Canary secret disclosures (critical indirect prompt injection indicator)
2. Sensitive API credentials / secrets leakage
3. Malicious URI schemes and unsafe HTML markup (e.g. javascript:, <script>)
4. Grounding & citation validity against authorized evidence
"""
from __future__ import annotations

import re
from typing import Any, Optional

from pydantic import BaseModel, Field

from app.core.logging import get_logger
from app.services.canary_service import canary_service
from app.services.retrieval_service import RetrievedChunk
from app.services.security_policy_engine import (
    PolicyDecision,
    PolicyEvaluationResult,
    ReasonCode,
    policy_engine,
)

logger = get_logger(__name__)


# Known credential patterns
CREDENTIAL_PATTERNS = [
    # Google Gemini / Cloud API Key
    (re.compile(r"\bAIza[0-9A-Za-z\-_]{35}\b"), "[REDACTED_GEMINI_KEY]"),
    # OpenAI / Anthropic API Keys
    (re.compile(r"\b(?:sk|sk-ant)-[A-Za-z0-9_\-]{20,}\b"), "[REDACTED_API_KEY]"),
    # GitHub Personal Access Tokens
    (re.compile(r"\bgh[pousr]_[A-Za-z0-9_]{36,}\b"), "[REDACTED_GITHUB_TOKEN]"),
    # Generic Authorization Bearer tokens
    (re.compile(r"\bBearer\s+[A-Za-z0-9\-_\.]{24,}\b", re.IGNORECASE), "Bearer [REDACTED_BEARER_TOKEN]"),
    # Generic Private Key Headers
    (re.compile(r"-----BEGIN\s+(?:RSA\s+)?PRIVATE\s+KEY-----.*?-----END\s+(?:RSA\s+)?PRIVATE\s+KEY-----", re.DOTALL), "[REDACTED_PRIVATE_KEY]"),
]

# Unsafe schemes & script tags
UNSAFE_SCHEMES_PATTERN = re.compile(r"\b(?:javascript|vbscript|data):[^\s\)\"\'>]+", re.IGNORECASE)
SCRIPT_TAG_PATTERN = re.compile(r"<\s*(?:script|iframe|object|embed)[^>]*>.*?<\s*/\s*(?:script|iframe|object|embed)\s*>", re.IGNORECASE | re.DOTALL)


class OutputSecurityResult(BaseModel):
    """Result of post-generation security and sanitization checks."""

    is_allowed: bool
    is_blocked: bool
    policy_decision: PolicyDecision
    reason_code: ReasonCode
    severity: str
    sanitized_content: str
    canary_leaked: bool = False
    credential_leaked: bool = False
    unsafe_schema_detected: bool = False
    signals: list[dict[str, Any]] = Field(default_factory=list)
    explanation: str


class OutputSecurityService:
    """Centralized scanner and sanitizer for LLM output text."""

    def inspect_and_sanitize(
        self,
        output_text: str,
        authorized_chunks: Optional[list[RetrievedChunk]] = None,
        active_canary: Optional[str] = None,
    ) -> OutputSecurityResult:
        """
        Screen and sanitize generated LLM response.

        Args:
            output_text: Raw output string generated by LLM.
            authorized_chunks: Chunks passed into context (for citation verification).
            active_canary: Optional active session canary token to watch for.

        Returns:
            OutputSecurityResult with safe content or refusal block.
        """
        if not output_text:
            return OutputSecurityResult(
                is_allowed=True,
                is_blocked=False,
                policy_decision=PolicyDecision.ALLOW,
                reason_code=ReasonCode.NORMAL,
                severity="low",
                sanitized_content="",
                explanation="Empty output.",
            )

        working_text = output_text
        signals: list[dict[str, Any]] = []

        # 1. Canary Leakage Detection (CRITICAL)
        canary_leaked = canary_service.has_canary_leak(working_text, specific_canary=active_canary)
        if canary_leaked:
            detected_canaries = canary_service.detect_canaries(working_text)
            signals.append({
                "type": "canary_leakage",
                "severity": "critical",
                "canary_count": len(detected_canaries),
                "description": "Server canary secret found in LLM response",
            })
            eval_res = policy_engine.evaluate_output_policy(
                canary_leaked=True,
                credential_leaked=False,
                unsafe_schema_detected=False,
                signals=signals,
            )
            logger.error(
                "CRITICAL SECURITY ALERT: Canary secret leaked in LLM output",
                extra={"detected_count": len(detected_canaries)},
            )
            # Fail closed: completely block output
            refusal_content = (
                "The response generated by the AI agent was blocked by the SentinelRAG Security Gateway "
                "because it contained an unauthorized internal canary secret. This indicates an indirect "
                "prompt injection or data leakage attempt was detected and neutralized."
            )
            return OutputSecurityResult(
                is_allowed=False,
                is_blocked=True,
                policy_decision=eval_res.decision,
                reason_code=eval_res.reason_code,
                severity=eval_res.severity,
                sanitized_content=refusal_content,
                canary_leaked=True,
                signals=signals,
                explanation=eval_res.explanation,
            )

        # 2. Credential & Secret Leakage Inspection
        credential_leaked = False
        for pattern, replacement in CREDENTIAL_PATTERNS:
            if pattern.search(working_text):
                credential_leaked = True
                working_text = pattern.sub(replacement, working_text)
                signals.append({
                    "type": "credential_leakage",
                    "severity": "high",
                    "replacement": replacement,
                })

        # 3. Malicious Schema & Script Tag Sanitization
        unsafe_schema_detected = False
        if UNSAFE_SCHEMES_PATTERN.search(working_text):
            unsafe_schema_detected = True
            working_text = UNSAFE_SCHEMES_PATTERN.sub("#blocked-unsafe-uri", working_text)
            signals.append({
                "type": "malicious_uri_scheme",
                "severity": "medium",
                "description": "Unsafe URI scheme (javascript/data/vbscript) neutralized",
            })

        if SCRIPT_TAG_PATTERN.search(working_text):
            unsafe_schema_detected = True
            working_text = SCRIPT_TAG_PATTERN.sub("[REMOVED_UNSAFE_EMBED]", working_text)
            signals.append({
                "type": "unsafe_markup",
                "severity": "medium",
                "description": "Unsafe HTML script or object tag removed",
            })

        # Evaluate through policy engine
        eval_res = policy_engine.evaluate_output_policy(
            canary_leaked=False,
            credential_leaked=credential_leaked,
            unsafe_schema_detected=unsafe_schema_detected,
            signals=signals,
        )

        return OutputSecurityResult(
            is_allowed=eval_res.is_allowed,
            is_blocked=not eval_res.is_allowed,
            policy_decision=eval_res.decision,
            reason_code=eval_res.reason_code,
            severity=eval_res.severity,
            sanitized_content=working_text,
            canary_leaked=False,
            credential_leaked=credential_leaked,
            unsafe_schema_detected=unsafe_schema_detected,
            signals=signals,
            explanation=eval_res.explanation,
        )


output_security_service = OutputSecurityService()

